#!/bin/sh
# Refuse a Data/Snapshot.lua that carries real saved data.
#
# The file ships with nothing in it but comments and must stay that way. Real
# saved data now goes to Interface\AddOns\Blackthornes_TS_Data instead, but an
# older copy of tools/restore.ps1 still writes here, and it holds characters,
# prices and auctions. Git tracks the file, so .gitignore cannot protect it;
# this does.
#
# The rule is now "no assignment to the global", where it used to be "assigns
# the global to nil". That inversion is the fix for a real bug: the data addon
# loads first and sets BlackthornesTSSnapshot, and this file loads first within
# the addon, so the nil ran over the top of the database and the session
# started empty. A generated copy assigns the global too, so one rule catches
# both.
#
# Reads the file's contents on stdin. Exits 0 when it is the empty shipped
# version, 1 when it holds data or code.

content=$(cat)

if printf '%s\n' "$content" | grep -q 'GENERATED by tools/restore.ps1'; then
    echo 'Data/Snapshot.lua was generated by tools/restore.ps1 and holds your saved data.'
    exit 1
fi

if printf '%s\n' "$content" | grep -n '^[[:space:]]*BlackthornesTSSnapshot[[:space:]]*='; then
    echo
    echo 'Data/Snapshot.lua assigns BlackthornesTSSnapshot. It must not: the local'
    echo 'data addon sets that global before this file loads, so an assignment here'
    echo 'runs over the top of the database it handed over.'
    exit 1
fi

# Anything that is not a comment or blank is code, and this file has no code.
if printf '%s\n' "$content" |
    grep -vq -e '^[[:space:]]*$' -e '^[[:space:]]*--'; then
    echo 'Data/Snapshot.lua has something in it other than comments.'
    exit 1
fi

exit 0

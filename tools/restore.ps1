<#
.SYNOPSIS
    Carry the price database from the last session into the next one.

.DESCRIPTION
    The WoW: Forever beta writes SavedVariables correctly but does not hand
    them back at load, so every session starts from an empty database. The
    addon's CVar store covers a /reload and a trip to character select, but
    those never end the client process; closing the game loses it.

    Ordinary addon files do still load. So this script copies the saved data
    into a tiny second addon, Blackthornes_TS_Data, which the main addon reads
    when the client hands back nothing.

    That addon lives in the game folder and never in the repository. An
    earlier version of this script wrote into Data\Snapshot.lua inside the
    working copy, which put real characters and prices a `git add -A` away
    from being committed. It also called deploy.ps1, which deletes its target
    folder -- and that target is now a junction to the working copy. Neither
    happens any more: this script only ever writes the one generated folder,
    and it backs the saved file up before it reads it.

    Run it after a session and before the next one, or use tools\play.ps1,
    which does both around launching the game.

.EXAMPLE
    .\tools\restore.ps1

.EXAMPLE
    .\tools\restore.ps1 -GamePath 'D:\Blizzard\World of Warcraft\_classic_beta_'
#>

[CmdletBinding()]
param(
    [string]$GamePath = 'D:\Blizzard\World of Warcraft\_classic_beta_',
    [string]$Account,
    [string]$BackupRoot
)

$ErrorActionPreference = 'Stop'

$accountRoot = Join-Path $GamePath 'WTF\Account'
if (-not (Test-Path $accountRoot)) {
    throw "No WTF\Account folder under $GamePath"
}

# Pick the account automatically when there is only one.
if (-not $Account) {
    $accounts = @(Get-ChildItem $accountRoot -Directory |
        Where-Object { $_.Name -ne 'SavedVariables' })

    if ($accounts.Count -eq 0) { throw 'No account folders found.' }
    if ($accounts.Count -gt 1) {
        throw "Several accounts found ($($accounts.Name -join ', ')). Pass -Account."
    }

    $Account = $accounts[0].Name
}

$savedDir = Join-Path $accountRoot "$Account\SavedVariables"
$mainFile = Join-Path $savedDir 'Blackthornes_TS.lua'
$backupFile = Join-Path $savedDir 'Blackthornes_TS.lua.bak'

# The client starts each session empty and writes that emptiness out at
# logout, so the newest file is often the poorest. WoW keeps exactly one
# generation in the .bak, which a second such session would spend. Take
# whichever holds more, and keep our own dated copy before anything else --
# this is the only copy of the price history that exists.
$candidates = @($mainFile, $backupFile) | Where-Object { Test-Path $_ }

if ($candidates.Count -eq 0) {
    throw "No saved data in $savedDir. Play a session and /reload first."
}

if (-not $BackupRoot) {
    $BackupRoot = Join-Path $GamePath 'WTF\BlackthornesTS_Backups'
}

$stamp = Get-Date -Format 'yyyy-MM-dd_HHmm'
$backupDir = Join-Path $BackupRoot $stamp
New-Item -ItemType Directory -Path $backupDir -Force | Out-Null

foreach ($file in $candidates) {
    Copy-Item $file (Join-Path $backupDir (Split-Path $file -Leaf)) -Force
}

Write-Host "Backed up $($candidates.Count) saved file(s) to $backupDir" -ForegroundColor Green

$savedFile = ($candidates | Sort-Object { (Get-Item $_).Length } -Descending)[0]

if ($savedFile -eq $backupFile) {
    Write-Host 'Using the .bak copy: it holds more than the latest write.' -ForegroundColor Yellow
}

$saved = Get-Content $savedFile -Raw

if ([string]::IsNullOrWhiteSpace($saved) -or $saved -notmatch 'BlackthornesTSDB') {
    throw "The saved file has no database in it ($savedFile). Nothing to carry over."
}

# Same data under a different global, so the addon can tell a fallback from a
# database the client genuinely handed back.
$body = $saved -replace 'BlackthornesTSDB\s*=', 'BlackthornesTSSnapshot ='

$addonRoot = Join-Path $GamePath 'Interface\AddOns\Blackthornes_TS_Data'

# Created, never cleared: nothing here removes a directory, so a wrong
# -GamePath produces a stray folder rather than a deletion.
New-Item -ItemType Directory -Path $addonRoot -Force | Out-Null

$toc = @"
## Interface: 16001
## Title: Blackthornes Tradeskills |cff7a8089(saved data)|r
## Notes: Local price history for Blackthornes Tradeskills. Generated by tools\restore.ps1 -- do not distribute.
## Author: Blackthornes
## Version: 0.1.0

Data.lua
"@

$header = @"
-- Blackthornes Tradeskills -- local saved data.
--
-- GENERATED by tools\restore.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm') from
-- $(Split-Path $savedFile -Leaf). Do not edit, and do not share this file: it
-- holds real characters, prices and auctions.
--
-- It exists because this client writes SavedVariables and does not read them
-- back. Config:Bootstrap seeds from it when the client hands back nothing,
-- and ignores it when the real database loads.

BlackthornesTSSnapshotSource = "Blackthornes_TS_Data, written $(Get-Date -Format 'yyyy-MM-dd HH:mm')"

"@

# PowerShell 5.1's -Encoding UTF8 prepends a byte-order mark, which WoW's Lua
# loader does not accept in an addon file. Write UTF-8 without one.
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

[System.IO.File]::WriteAllText((Join-Path $addonRoot 'Blackthornes_TS_Data.toc'), $toc, $utf8NoBom)
[System.IO.File]::WriteAllText((Join-Path $addonRoot 'Data.lua'), ($header + $body), $utf8NoBom)

$sizeKb = [math]::Round((Get-Item (Join-Path $addonRoot 'Data.lua')).Length / 1KB, 1)

Write-Host "Wrote Blackthornes_TS_Data from $Account ($sizeKb KB)." -ForegroundColor Green
Write-Host 'Next login restores from it. Check with /bts persist in game.' -ForegroundColor Yellow

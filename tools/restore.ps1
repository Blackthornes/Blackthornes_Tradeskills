<#
.SYNOPSIS
    Rebuild the persistence snapshot from the game's saved-variable file.

.DESCRIPTION
    The WoW: Forever beta writes SavedVariables correctly but does not read them
    back, so every relog starts from an empty database. Ordinary addon files do
    still load, so this script copies the saved data into the addon itself as
    Data\Snapshot.lua, under a different global. The addon seeds from it when
    the client hands back nothing.

    Run this after a play session (once the game has written the file, which
    happens on /reload or logout) and before the next one.

    When Blizzard fixes SavedVariables loading, the real database takes
    precedence and the snapshot is ignored.

.EXAMPLE
    .\tools\restore.ps1
#>

[CmdletBinding()]
param(
    [string]$GamePath = 'D:\Blizzard\World of Warcraft\_classic_beta_',
    [string]$Account,
    [switch]$SkipDeploy
)

$ErrorActionPreference = 'Stop'

$ProjectRoot = Split-Path $PSScriptRoot -Parent
$SnapshotFile = Join-Path $ProjectRoot 'Data\Snapshot.lua'

$accountRoot = Join-Path $GamePath 'WTF\Account'
if (-not (Test-Path $accountRoot)) {
    throw "No WTF\Account folder under $GamePath"
}

# Pick the account automatically when there is only one.
if (-not $Account) {
    $accounts = @(Get-ChildItem $accountRoot -Directory |
        Where-Object { $_.Name -ne 'SavedVariables' })

    if ($accounts.Count -eq 0) { throw 'No account folders found.' }
    if ($accounts.Count -gt 1) {
        throw "Several accounts found ($($accounts.Name -join ', ')). Pass -Account."
    }

    $Account = $accounts[0].Name
}

$savedDir = Join-Path $accountRoot "$Account\SavedVariables"
$mainFile = Join-Path $savedDir 'Blackthornes_TS.lua'
$backupFile = Join-Path $savedDir 'Blackthornes_TS.lua.bak'

# The client wipes the database every session, so the most recent write is
# often the emptiest. Take whichever copy still holds the most data, and say
# which one was used rather than silently picking.
$candidates = @($mainFile, $backupFile) | Where-Object { Test-Path $_ }

if ($candidates.Count -eq 0) {
    throw "No saved data in $savedDir. Play a session and /reload first."
}

$savedFile = ($candidates | Sort-Object { (Get-Item $_).Length } -Descending)[0]

if ($savedFile -eq $backupFile) {
    Write-Host 'Using the backup copy: it holds more than the latest write.' -ForegroundColor Yellow
}

$saved = Get-Content $savedFile -Raw

if ([string]::IsNullOrWhiteSpace($saved) -or $saved -notmatch 'BlackthornesTSDB') {
    throw 'The saved-variable file has no database in it. Nothing to snapshot.'
}

# Same data, different global: the addon treats it as a fallback, never as the
# live database.
$body = $saved -replace 'BlackthornesTSDB\s*=', 'BlackthornesTSSnapshot ='

$header = @"
-- Blackthornes Tradeskills -- Data/Snapshot.lua
--
-- GENERATED by tools/restore.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm'). Do not edit.
--
-- A persistence fallback for the WoW: Forever beta, which writes SavedVariables
-- but does not read them back. Config:Bootstrap seeds from this when the client
-- hands back nothing, and ignores it when the real database loads.

"@

# PowerShell 5.1's -Encoding UTF8 prepends a byte-order mark, which WoW's Lua
# loader does not accept in an addon file. Write UTF-8 without one.
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($SnapshotFile, ($header + $body), $utf8NoBom)

$sizeKb = [math]::Round((Get-Item $SnapshotFile).Length / 1KB, 1)
Write-Host "Snapshot written from $Account ($sizeKb KB)." -ForegroundColor Green

if (-not $SkipDeploy) {
    & (Join-Path $ProjectRoot 'deploy.ps1') -GamePath $GamePath
}

Write-Host 'Next login will restore from this snapshot.' -ForegroundColor Yellow

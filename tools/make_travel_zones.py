"""Writes Data/TravelZones.lua: the zones the arrow's trips walk through
(Logic/Travel.lua), the same file in every Blackthornes addon.

Run from the repository root, naming a checkout of Blackthornes Farmer:

    python tools/make_travel_zones.py <Blackthornes_Farmer folder>

It reads only Farmer's own files:

- Data/Zones.lua (written by Farmer's tools/make_zones.py from the Forever
  client's game tables): each zone's map ID, by its English name.
- Logic/Spots.lua: which zone borders which (BORDERS), and the capitals
  that sit inside a zone (INSIDE, cities only; dungeons are left out).
- Data/Travel.lua (tools/make_travel.py): the short zone names the flight
  masters carry ("Elwynn" in "Stormwind, Elwynn"), each matched to the one
  zone whose name starts with it.

What it writes:

- maps[zone] = map ID, by the English name.
- borders[zone] = { zones it borders }. Boats and flights are not borders.
- inside[city] = the zone it sits in.
- aliases[short name] = zone.

Never edit the output by hand; rerun this when any of those files change,
and copy the output to every addon with Logic/Travel.lua.
"""

import re
import sys
from pathlib import Path

OUT = Path("Data/TravelZones.lua")

PAIR = re.compile(r'\["([^"]+)"\]\s*=\s*(\d+)')
NAMED = re.compile(r'\["([^"]+)"\]\s*=\s*"([^"]+)"')
LIST = re.compile(r'\["([^"]+)"\]\s*=\s*\{([^}]*)\}')
STRING = re.compile(r'"([^"]+)"')
FLIGHT_ZONE = re.compile(r'\{\s*"[^"]*",\s*"[AH]+",\s*\d+,\s*[-\d.]+,\s*[-\d.]+,\s*"([^"]+)"\s*\}')
DOCK_ZONE = re.compile(r'=\s*\{\s*"[^"]*",\s*\d+,\s*[-\d.]+,\s*[-\d.]+,\s*"([^"]+)"\s*\}')


def block(text, start, name):
    """The text of `local NAME = { ... }` (or `NAME = {`), braces matched."""
    at = text.find(start)
    if at < 0:
        sys.exit(f"{name} not found")
    at = text.index("{", at)
    depth = 0
    for index in range(at, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[at + 1:index]
    sys.exit(f"{name} is not closed")


def read(farmer):
    zones = (farmer / "Data/Zones.lua").read_text(encoding="utf-8")
    spots = (farmer / "Logic/Spots.lua").read_text(encoding="utf-8")
    travel = (farmer / "Data/Travel.lua").read_text(encoding="utf-8")

    maps = {name: int(number) for name, number in PAIR.findall(block(zones, "maps = {", "maps"))}

    borders = {}
    for zone, inner in LIST.findall(block(spots, "local BORDERS = {", "BORDERS")):
        borders[zone] = STRING.findall(inner)

    inside = {}
    for city, zone in NAMED.findall(block(spots, "local INSIDE = {", "INSIDE")):
        if city in maps and zone in maps:
            inside[city] = zone

    aliases = {}
    for short in sorted(set(FLIGHT_ZONE.findall(travel)) | set(DOCK_ZONE.findall(travel))):
        if short in maps:
            continue
        found = [zone for zone in maps if zone.startswith(short + " ")]
        if len(found) == 1:
            aliases[short] = found[0]
    return maps, borders, inside, aliases


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(maps, borders, inside, aliases):
    out = [
        "-- Blackthornes -- Data/TravelZones.lua",
        "-- Generated by tools/make_travel_zones.py from Blackthornes Farmer's zone",
        "-- data (itself from the Forever client's game tables); never edit by hand.",
        "-- The same file in every addon with Logic/Travel.lua.",
        "",
        "local _, ns = ...",
        "",
        "ns.TRAVEL_ZONES = {",
        "    -- [zone] = map ID",
        "    maps = {",
    ]
    for zone in sorted(maps, key=lambda name: (maps[name], name)):
        out.append(f"        [{lua_string(zone)}] = {maps[zone]},")
    out += ["    },", "", "    -- [zone] = { the zones it borders }", "    borders = {"]
    for zone in sorted(borders):
        inner = ", ".join(lua_string(near) for near in borders[zone])
        out.append(f"        [{lua_string(zone)}] = {{ {inner} }}," if inner else f"        [{lua_string(zone)}] = {{}},")
    out += ["    },", "", "    -- [city] = the zone it sits in", "    inside = {"]
    for city in sorted(inside):
        out.append(f"        [{lua_string(city)}] = {lua_string(inside[city])},")
    out += ["    },", "", "    -- [the flight masters' short name] = zone", "    aliases = {"]
    for short in sorted(aliases):
        out.append(f"        [{lua_string(short)}] = {lua_string(aliases[short])},")
    out += ["    },", "}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    write(*read(Path(sys.argv[1])))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()

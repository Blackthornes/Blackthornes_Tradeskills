"""Writes Data/VendorPrices.lua: what vendors sell materials for.

Run from the repository root with the mangoszero world database's
item_template.sql and npc_vendor.sql (World/Setup/FullDB in
github.com/mangoszero/database) in a folder:

    python tools/make_vendor_prices.py <folder>

Only items more vendors sell without a stock limit than with one are kept,
from the item classes crafting draws on: consumables (0), reagents (5) and
trade goods (7). A limited-stock item (a herb from one shop) cannot supply a
run of crafts, so it is left to the price the addon learns when that vendor
is opened. One shop is not enough on its own: the database has a single
engineering supplier selling Copper Modulators, Bronze Tubes and the like
without a limit, against ten or more that sell two at a time, and the table
priced them at 2s and 8s while the auction house wanted 15s and 6s
(2026-10-09).
"""

import collections
import re
import sys
from pathlib import Path

CLASSES = {0: "Consumable", 5: "Reagent", 7: "Trade goods"}

ROW = re.compile(
    r"^\((\d+),(\d+),(\d+),'((?:[^'\\]|\\.)*)',(\d+),(\d+),(-?\d+),(\d+),(\d+),"
)
VENDOR = re.compile(r"\((\d+),(\d+),(\d+),(\d+),(\d+)\)")


def load(folder):
    items = {}
    with open(folder / "item_template.sql", encoding="utf-8", errors="replace") as f:
        for line in f:
            m = ROW.match(line)
            if m:
                entry, cls, _sub, name, _disp, _q, _flags, count, price = m.groups()
                items[int(entry)] = (int(cls), name.replace("\\'", "'"), int(count), int(price))

    unlimited = collections.Counter()
    limited = collections.Counter()
    with open(folder / "npc_vendor.sql", encoding="utf-8") as f:
        for line in f:
            for m in VENDOR.finditer(line):
                _npc, item, maxcount, _incr, _cond = map(int, m.groups())
                if maxcount == 0:
                    unlimited[item] += 1
                else:
                    limited[item] += 1
    return items, {item for item in unlimited if unlimited[item] > limited[item]}


def main():
    folder = Path(sys.argv[1])
    items, unlimited = load(folder)

    groups = collections.defaultdict(list)
    for itemID in sorted(unlimited):
        if itemID not in items:
            continue
        cls, name, count, price = items[itemID]
        if cls not in CLASSES or price <= 0:
            continue
        # Sold in bundles (5 vials for 20c); the table holds one unit.
        unit = price / max(1, count)
        unit = int(unit) if unit == int(unit) else round(unit, 2)
        groups[cls].append((itemID, unit, name))

    out = [
        "-- Blackthornes Tradeskills -- Data/VendorPrices.lua",
        "-- What vendors sell materials for, in copper for one unit, by item ID.",
        "--",
        "-- Generated by tools/make_vendor_prices.py from Classic 1.12 data (the",
        "-- mangoszero world database), not typed by hand. Only items more vendors",
        "-- sell without a stock limit than with one are here. A price learned from",
        "-- a vendor in game (Data/Vendor.lua) always wins over this table, so a",
        "-- shop that charges differently on Forever corrects it the first time it",
        "-- is opened.",
        "",
        "local _, ns = ...",
        "",
        "ns.VENDOR_PRICES = {",
    ]
    for cls in sorted(groups):
        out.append(f"    -- {CLASSES[cls]}")
        for itemID, unit, name in groups[cls]:
            out.append(f"    [{itemID}] = {unit}, -- {name}")
    out.append("}")
    Path("Data/VendorPrices.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(sum(len(g) for g in groups.values()), "items")


if __name__ == "__main__":
    main()

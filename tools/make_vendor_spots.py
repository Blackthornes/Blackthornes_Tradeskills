"""Writes Data/VendorSpots.lua: where the vendors stand who sell materials.

Run from the repository root with the same quest database folder as
make_learn_spots.py:

    python tools/make_vendor_spots.py <quest database>

Its db/ says which NPCs sell each item, whether in a limited number,
where every NPC stands in zone map coordinates and which faction it serves.
Only the items in Data/VendorPrices.lua are kept (materials most vendors
sell without a limit), and only vendors that sell them without a limit, for
the vendor map pins (Logic/VendorPins.lua). A vendor the player opens in
game is learned on top of this, so Forever's own shops show up too.

Nothing in the output is typed by hand.
"""

import collections
import re
import sys
from pathlib import Path

from lupa import lua51

ROOT = Path(__file__).resolve().parent.parent
PRICES = ROOT / "Data" / "VendorPrices.lua"
OUT = ROOT / "Data" / "VendorSpots.lua"


def load_quest_db(folder):
    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    lua.execute("pfDB = setmetatable({}, {__index = function(t, k) "
                "local v = {} rawset(t, k, v) return v end})")
    db = folder / "db"
    for name in ["units.lua", "items.lua", "zones.lua", "enUS/units.lua", "enUS/zones.lua"]:
        lua.execute((db / name).read_text(encoding="utf-8"))
    return lua.eval("pfDB")


def lua_table(t):
    return {k: t[k] for k in t} if t is not None else {}


def place(entry, zone_names):
    """The zone an NPC mostly stands in, and one spot there."""
    coords = entry and entry["coords"]
    if not coords:
        return None
    spots = [coords[i] for i in coords]
    spots = [s for s in spots if zone_names[s[3]]]
    if not spots:
        return None
    zone = collections.Counter(s[3] for s in spots).most_common(1)[0][0]
    for s in spots:
        if s[3] == zone:
            return zone_names[zone], round(float(s[1]), 1), round(float(s[2]), 1)
    return None


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(x):
    if x == int(x):
        return str(int(x))
    return str(x)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    quest_db = load_quest_db(Path(sys.argv[1]))
    wanted = sorted({int(m) for m in re.findall(r"^\s*\[(\d+)\] = \d+,", PRICES.read_text(encoding="utf-8"), re.M)})

    units, unit_names = quest_db["units"]["data"], quest_db["units"]["enUS"]
    zone_names = quest_db["zones"]["enUS"]
    pf_items = quest_db["items"]["data"]

    npcs, sells = {}, {}
    for item_id in wanted:
        entry = pf_items[item_id]
        if not entry or not entry["V"]:
            continue
        ids = []
        for uid, stock in sorted(lua_table(entry["V"]).items()):
            if stock and int(stock) > 0:
                continue  # a limited number: not one to send the player to
            if uid not in npcs:
                where = place(units[uid], zone_names)
                name = unit_names[uid]
                npcs[uid] = (name, *where, units[uid]["fac"] or "") if where and name else None
            if npcs[uid]:
                ids.append(uid)
        if ids:
            sells[item_id] = ids

    used = sorted({uid for ids in sells.values() for uid in ids})
    out = [
        "-- Blackthornes Tradeskills -- Data/VendorSpots.lua",
        "-- Where the vendors stand who sell materials, for the vendor map pins",
        "-- (Logic/VendorPins.lua). Generated by tools/make_vendor_spots.py, never",
        "-- typed by hand. Classic's vendors; a shop opened in game is learned on top.",
        "",
        "local _, ns = ...",
        "",
        "local Spots = {}",
        "ns.VENDOR_SPOTS = Spots",
        "",
        "-- [npc ID] = { name, zone, x, y, side (\"A\", \"H\", or \"\" for both) }",
        "Spots.NPCS = {",
    ]
    for uid in used:
        name, zone, x, y, fac = npcs[uid]
        side = fac if fac in ("A", "H") else ""
        out.append(f"    [{uid}] = {{ {lua_string(name)}, {lua_string(zone)}, {num(x)}, {num(y)}, \"{side}\" }},")
    out += ["}", "", "-- [item ID] = { npc ID, ... } that sell it without a limit", "Spots.ITEMS = {"]
    for item_id in sorted(sells):
        out.append(f"    [{item_id}] = {{ {', '.join(str(u) for u in sells[item_id])} }},")
    out += ["}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {len(used)} vendors for {len(sells)} items")


if __name__ == "__main__":
    main()

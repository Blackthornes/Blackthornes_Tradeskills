"""Writes Data/ForeverTrainerRecipes.lua: what profession trainers teach on
WoW: Forever, with the skill each asks for and its price, as the game's
trainer windows showed them, so every player gets them before they visit.

Run from the repository root:

    python tools/forever_trainer_recipes.py [saved file ...]

A saved file is the addon's account save, Blackthornes_TS.lua from the
game's WTF/Account/<account>/SavedVariables folder. Only its
`trainerRecipes` table is read (Logic/TrainerRecipes.lua: recipe ID ->
cost, skill and when it was seen), so nothing about the player or their
characters is copied. When it was seen is not written out.

The rows already in Data/ForeverTrainerRecipes.lua are kept, and a reading
from a save replaces them (the newest when several saves name a recipe).

Options:
    --stdout   print the file instead of writing it
"""

import os
import sys

from lupa import lua51

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "Data", "ForeverTrainerRecipes.lua")

# A save is read as data: run in an empty table with nothing to call, so a
# file that is not what it seems can reach neither the disk nor Python.
# Compiled chunks are refused, since they could get round that.
READ = """
function(text, name)
    if text:sub(1, 1) == "\\27" then return nil, "a compiled file" end
    local chunk, err = loadstring(text, "=file")
    if not chunk then return nil, err end
    local env = {}
    if name == "shipped" then env.ns = {} end
    setfenv(chunk, env)
    local ok, why = pcall(chunk, nil, env.ns)
    if not ok then return nil, why end
    if name == "shipped" then return env.ns.FOREVER_TRAINER_RECIPES, false end
    return env.BlackthornesTSDB, false
end
"""

HEADER = """-- Blackthornes Tradeskills -- Data/ForeverTrainerRecipes.lua
-- What profession trainers teach on Forever: recipe ID -> { skill the
-- trainer asks for, price in copper }. Read by Logic/TrainerRecipes.lua;
-- a character's own trainer visits win.
--
-- Generated by tools/forever_trainer_recipes.py. Do not edit by hand:
-- rerun the tool.

local _, ns = ...

ns.FOREVER_TRAINER_RECIPES = {
"""


def whole(value, low=0, high=10 ** 9):
    """A whole number from low to high, else None."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    if value != value or value < low or value > high:
        return None
    return int(value)


def read(lua, path, name):
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        text = handle.read()
    table, why = lua.eval(READ)(text, name)
    if table is None:
        raise SystemExit("could not read %s: %s" % (path, why))
    return table


def shipped(lua):
    """{ recipeID: (skill, cost, 0) } from the file as it stands."""
    found = {}
    if not os.path.exists(OUTPUT):
        return found
    table = read(lua, OUTPUT, "shipped") or {}
    for key in list(table.keys()):
        row = table[key]
        recipe = whole(key, 1)
        if recipe is None or lua51.lua_type(row) != "table":
            continue
        found[recipe] = (whole(row[1], 0, 1000) or 0, whole(row[2]) or 0, 0)
    return found


def from_save(lua, path):
    """{ recipeID: (skill, cost, seen at) } from one save."""
    found = {}
    db = read(lua, path, "save")
    table = db and db["trainerRecipes"]
    if lua51.lua_type(table) != "table":
        return found
    for key in list(table.keys()):
        row = table[key]
        recipe = whole(key, 1)
        if recipe is None or lua51.lua_type(row) != "table":
            continue
        skill, cost = whole(row["skill"], 0, 1000), whole(row["cost"])
        if skill is None and cost is None:
            continue
        found[recipe] = (skill or 0, cost or 0, whole(row["at"]) or 0)
    return found


def render(rows):
    out = [HEADER]
    for recipe in sorted(rows):
        skill, cost, _ = rows[recipe]
        out.append("    [%d] = { %d, %d },\n" % (recipe, skill, cost))
    out.append("}\n")
    return "".join(out)


def main(argv):
    to_stdout = "--stdout" in argv
    paths = [a for a in argv if not a.startswith("--")]
    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    rows = shipped(lua)
    newest = {}
    for path in paths:
        for recipe, row in from_save(lua, path).items():
            if recipe not in newest or row[2] >= newest[recipe][2]:
                newest[recipe] = row
    rows.update(newest)
    text = render(rows)
    if to_stdout:
        sys.stdout.write(text)
    else:
        with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("%d trainer recipes (%d from saves) in %s" % (len(rows), len(newest), os.path.relpath(OUTPUT, ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
